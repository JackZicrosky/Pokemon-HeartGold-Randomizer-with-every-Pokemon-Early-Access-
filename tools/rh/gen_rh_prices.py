#!/usr/bin/env python3
# Romhack: UPR FVX's "Balance Shop Prices" table, as in the FireRed/Emerald romhack (its tools/rh/gen_prices.py):
# FVX's Gen 4 list (this game) wins, its Gen 7 list adds the modern items (not its TMs: other moves).
# Input: FVX's romio/src/main/java/com/uprfvx/romio/constants/Gen{4,7}Constants.java (github.com/upr-fvx), copied to
# tools/rh/ref/fvx_balanced_prices.txt by this script when given the folder. Writes include/rh/rh_balanced_prices.h
# (sorted by item id, binary searched by src/item.c).
# Usage: python3 tools/rh/gen_rh_prices.py [FVX_CONSTANTS_DIR]   (from the repository root)
import re
import sys

REF = 'tools/rh/ref/fvx_balanced_prices.txt'
ALIAS = {'ITEM_THUNDERSTONE': 'ITEM_THUNDER_STONE', 'ITEM_PARLYZ_HEAL': 'ITEM_PARALYZE_HEAL',
         'ITEM_ENERGYPOWDER': 'ITEM_ENERGY_POWDER', 'ITEM_TINYMUSHROOM': 'ITEM_TINY_MUSHROOM',
         'ITEM_NEVERMELTICE': 'ITEM_NEVER_MELT_ICE', 'ITEM_SILVERPOWDER': 'ITEM_SILVER_POWDER',
         'ITEM_TWISTEDSPOON': 'ITEM_TWISTED_SPOON', 'ITEM_BRIGHTPOWDER': 'ITEM_BRIGHT_POWDER',
         'ITEM_DEEPSEATOOTH': 'ITEM_DEEP_SEA_TOOTH', 'ITEM_DEEPSEASCALE': 'ITEM_DEEP_SEA_SCALE',
         'ITEM_UPGRADE': 'ITEM_UP_GRADE'}


MAIL = ['GRASS', 'FLAME', 'BUBBLE', 'BLOOM', 'TUNNEL', 'STEEL', 'HEART', 'SNOW', 'SPACE', 'AIR', 'MOSAIC', 'BRICK']


def snake(n):
    m = re.match(r'tm(\d+)$', n)
    if m:
        return 'ITEM_TM%03d' % int(m.group(1))
    m = re.match(r'mail(\d+)$', n)
    if m:
        return 'ITEM_%s_MAIL' % MAIL[int(m.group(1)) - 1]
    s = re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', n)
    s = re.sub(r'([A-Z])([A-Z][a-z])', r'\1_\2', s)
    return 'ITEM_' + s.upper()


def main():
    if len(sys.argv) > 1:
        lines = []
        for gen in ('7', '4'):                       # Gen 4 last: it wins
            src = open('%s/Gen%sConstants.java' % (sys.argv[1], gen), encoding='utf-8').read()
            block = src[src.index('balancedItemPrices'):]
            block = block[:block.index('}).collect')]
            for name, price in re.findall(r'\{ItemIDs\.(\w+),\s*(\d+)\}', block):
                if gen == '7' and re.match(r'(tm|hm|tr)\d+$', name, re.I):
                    continue
                lines.append('%s %s %s' % (gen, name, price))
        open(REF, 'w', newline='\n').write('# UPR FVX balancedItemPrices (generation, ItemIDs name, price)\n' + '\n'.join(lines) + '\n')
    ids = {}
    for m in re.finditer(r'#define (ITEM_\w+)\s+(\d+)', open('include/constants/item.h').read()):
        ids.setdefault(m.group(1), int(m.group(2)))
    prices, missing = {}, []
    for line in open(REF):
        if line.startswith('#'):
            continue
        gen, name, price = line.split()
        item = ALIAS.get(snake(name), snake(name))
        if item in ids:
            prices[ids[item]] = (item, int(price))
        else:
            missing.append(name)
    out = ['// AUTO-GENERATED by tools/rh/gen_rh_prices.py - UPR FVX balanced shop prices (Gen 4, + Gen 7 modern items)',
           '// {item, price} sorted by item id (src/item.c).',
           'static const u16 sRhBalancedPrices[][2] = {']
    out += ['    { %s, %d },' % (prices[k][0], min(prices[k][1], 65535)) for k in sorted(prices)]
    out.append('};')
    open('include/rh/rh_balanced_prices.h', 'w', newline='\n').write('\n'.join(out) + '\n')
    print(len(prices), 'prices;', len(missing), 'unmatched')


if __name__ == '__main__':
    main()
