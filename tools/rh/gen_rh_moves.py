#!/usr/bin/env python3
# Romhack: the move pool of the Moves & Movesets / TM / tutor randomizers (FVX rules), from data/Moves.c.
# Writes data/rh/RhMoves.c (a028 member 23): struct RhMoveFile { u16 count; u16 pad; struct RhMove moves[]; }.
# Usage: python3 tools/rh/gen_rh_moves.py   (from the repository root)
import re

SRC = 'data/Moves.c'
OUT = 'data/rh/RhMoves.c'

# FVX: only Struggle (and moves that can't work here) are banned from random picks.
UNUSABLE = {'STRUGGLE', 'STRUGGLE_BUG', 'HYPERSPACE_FURY', 'AURA_WHEEL', 'DARK_VOID'}
Z_MOVES = {'CATASTROPIKA', 'SINISTER_ARROW_RAID', 'MALICIOUS_MOONSAULT', 'OCEANIC_OPERETTA', 'GUARDIAN_OF_ALOLA',
           'SOUL_STEALING_7_STAR_STRIKE', 'STOKED_SPARKSURFER', 'PULVERIZING_PANCAKE', 'EXTREME_EVOBOOST',
           'GENESIS_SUPERNOVA', '10_000_000_VOLT_THUNDERBOLT', 'LIGHT_THAT_BURNS_THE_SKY', 'SEARING_SUNRAZE_SMASH',
           'MENACING_MOONRAZE_MAELSTROM', 'LETS_SNUGGLE_FOREVER', 'SPLINTERED_STORMSHARDS', 'CLANGOROUS_SOULBLAZE'}
# FVX "No Game-Breaking Moves": Sonic Boom and Dragon Rage; with Gen 1 rules also OHKO moves and Spore.
BROKEN = {'SONIC_BOOM', 'DRAGON_RAGE'}
GEN1_BROKEN = {'SPORE', 'HORN_DRILL', 'GUILLOTINE', 'FISSURE', 'SHEER_COLD'}
# FVX GlobalConstants.bannedForDamagingMove: never used as a forced / "good" attack.
NO_DAMAGING = {'SELF_DESTRUCT', 'DREAM_EATER', 'EXPLOSION', 'SNORE', 'FALSE_SWIPE', 'FUTURE_SIGHT', 'FAKE_OUT', 'FOCUS_PUNCH',
               'DOOM_DESIRE', 'FEINT', 'LAST_RESORT', 'SUCKER_PUNCH', 'CONSTRICT', 'RAGE', 'ROLLOUT', 'ICE_BALL',
               'SYNCHRONOISE', 'SHELL_TRAP', 'FOUL_PLAY', 'SPIT_UP', 'SONIC_BOOM', 'DRAGON_RAGE', 'HORN_DRILL',
               'GUILLOTINE', 'FISSURE', 'SHEER_COLD', 'MISTY_EXPLOSION', 'MIND_BLOWN', 'STEEL_BEAM', 'BELCH'}
# the HMs of HeartGold (level-up movesets never get them, FVX)
HMS = {'CUT', 'FLY', 'SURF', 'STRENGTH', 'WHIRLPOOL', 'ROCK_SMASH', 'WATERFALL', 'ROCK_CLIMB'}
HIT_TWICE = {'MOVE_EFFECT_HIT_TWICE', 'MOVE_EFFECT_HIT_TWICE_POISON', 'MOVE_EFFECT_HIT_TWICE_AND_FLINCH'}


def main():
    ids = {}
    for m in re.finditer(r'#define MOVE_(\w+)\s+(\d+)', open('include/constants/moves.h').read()):
        ids.setdefault(m.group(1), int(m.group(2)))
    src = open(SRC, encoding='utf-8').read()
    blocks = re.split(r'\n    \[MOVE_(\w+)\] = \{', src)
    pool = []
    for i in range(1, len(blocks), 2):
        name, b = blocks[i], blocks[i + 1]
        mid = ids.get(name)
        if not mid or name in UNUSABLE or name in Z_MOVES:
            continue
        if re.search(r'_(PHYSICAL|SPECIAL)$', name) or name.startswith('MAX_') or name.startswith('G_MAX_'):
            continue                                                 # Z-Moves and Max Moves
        flags = re.search(r'\.flags = ([^,\n]*)', b).group(1)
        if 'UNUSABLE' in flags:
            continue
        effect = re.search(r'\.effect = (\w+)', b).group(1)
        hits = 3 if effect == 'MOVE_EFFECT_MULTI_HIT' else (2 if effect in HIT_TWICE else 1)
        f = (1 if name in BROKEN else 0) | (2 if name in GEN1_BROKEN else 0) | (4 if name in NO_DAMAGING else 0) \
            | (8 if name in HMS else 0) | (hits << 4)
        pool.append((mid, name, f))
    pool.sort()
    out = ['// AUTO-GENERATED by tools/rh/gen_rh_moves.py from data/Moves.c - the randomizers\' move pool (a028 member 23).',
           '#include "../../include/types.h"',
           '#include "../../include/constants/moves.h"',
           '#include "../../include/rh/rh_data.h"',
           '',
           'const struct { u16 count, pad; struct RhMove moves[%d]; } sRhMoveFile = { %d, 0, {' % (len(pool), len(pool))]
    for mid, name, f in pool:
        out.append('    { MOVE_%s, 0x%02X, 0 },' % (name, f))
    out.append('} };')
    open(OUT, 'w', newline='\n').write('\n'.join(out) + '\n')
    print('wrote', OUT, len(pool), 'moves')


if __name__ == '__main__':
    main()
