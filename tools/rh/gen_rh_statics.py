#!/usr/bin/env python3
# Romhack: the Static Pokemon table, from UPR FVX's HeartGold (U) list (gen4_offsets.ini, StaticPokemon /
# StaticPokemonGameCorner / RoamingPokemon), copied to tools/rh/fvx_hgss_statics.txt.
# FVX patches species values inside map scripts; the romhack replaces the species at runtime in the script commands
# (wild battle, give Pokemon, give egg) on the maps whose scripts FVX names, and in the roamers.
# Writes data/rh/RhStatics.c (a028 member 26): u16 count, u16 pad, then {u16 map, u16 species} by index
# (map 0xFFFF = a roamer).
# Usage: python3 tools/rh/gen_rh_statics.py   (from the repository root)
import re
import struct

SRC = 'tools/rh/fvx_hgss_statics.txt'
MAP_HEADERS = 0xF6BE0
NUM_MAPS = 540

NAMES = {'Ho-oh': 'HO_OH', 'Giratina-O': 'GIRATINA', 'Red Gyarados': 'GYARADOS', "Primo's Mareep Egg": 'MAREEP',
         "Primo's Wooper Egg": 'WOOPER', "Primo's Slugma Egg": 'SLUGMA', 'Secret Tentacool': 'TENTACOOL',
         'Mr. Mime': 'MR_MIME'}


def species_of(name):
    name = re.sub(r' @.*| \(\d\)', '', name.strip())
    if name in NAMES:
        return NAMES[name]
    return name.upper().replace(' ', '_').replace('.', '').replace("'", '')


def main():
    arm9 = open('base/arm9.bin', 'rb').read()
    maps_of_script = {}
    for m in range(NUM_MAPS):
        o = MAP_HEADERS + m * 24
        scripts = struct.unpack('<H', arm9[o + 6:o + 8])[0]
        maps_of_script.setdefault(scripts, []).append(m)
    ids = {}
    for mm in re.finditer(r'#define SPECIES_(\w+)\s+(\d+)', open('include/constants/species.h').read()):
        ids.setdefault(mm.group(1), int(mm.group(2)))
    entries = []
    for line in open(SRC):
        mm = re.match(r'(StaticPokemon|StaticPokemonGameCorner|RoamingPokemon)\{\}=\{Species=\[([^\]]*)\].*// (.*)$', line.strip())
        if not mm:
            continue
        kind, offsets, name = mm.groups()
        sp = species_of(name)
        assert sp in ids, (name, sp)
        if kind == 'RoamingPokemon':
            entries.append((0xFFFF, sp, name))
            continue
        files = sorted({int(x.split(':')[0]) for x in offsets.split(',') if ':' in x})
        maps = sorted({m for f in files for m in maps_of_script.get(f, [])})
        for m in maps:
            entries.append((m, sp, name))
    # one entry per (map, species): e.g. the Rocket Base's Voltorb traps share one replacement, as in FVX
    seen, uniq = set(), []
    for m, sp, name in entries:
        if (m, sp) not in seen:
            seen.add((m, sp))
            uniq.append((m, sp, name))
    out = ['// AUTO-GENERATED by tools/rh/gen_rh_statics.py from UPR FVX\'s HeartGold static Pokemon list (a028 member 26).',
           '#include "../../include/types.h"',
           '#include "../../include/constants/species.h"',
           '#include "../../include/rh/rh_data.h"',
           '',
           'const struct { u16 count, pad; struct RhStatic statics[%d]; } sRhStaticFile = { %d, 0, {' % (len(uniq), len(uniq))]
    for m, sp, name in uniq:
        out.append('    { 0x%04X, SPECIES_%s }, // %s' % (m, sp, name))
    out.append('} };')
    open('data/rh/RhStatics.c', 'w', newline='\n').write('\n'.join(out) + '\n')
    print(len(uniq), 'statics')


if __name__ == '__main__':
    main()
