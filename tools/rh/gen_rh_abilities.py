#!/usr/bin/env python3
"""Romhack: which abilities actually work in this engine, for "Randomize Abilities".

The Gen 3-4 abilities are handled by the original game's code. Later abilities only work where hg-engine's
code handles them, so an ability counts as implemented when its constant appears in the engine's code
(src/, asm/, data/battle_scripts/), outside the data tables. Also takes "failsSwap" from data/AbilityFlags.c
(form / signature abilities: never randomized, like FireRed's "cantBeSwapped").

Writes src/rh/rh_abilities.h. Usage (WSL, in source/): python3 tools/rh/gen_rh_abilities.py
"""
import os
import re

R = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..')) + '/'
VANILLA_LAST = 123   # ABILITY_BAD_DREAMS: everything up to here is in the original HeartGold code


def main():
    consts = {}
    for m in re.finditer(r'^#define\s+(ABILITY_\w+)\s+(\d+)', open(R + 'include/constants/ability.h').read(), re.M):
        consts.setdefault(m.group(1), int(m.group(2)))
    count = max(consts.values()) + 1
    code = ''
    for d in ('src', 'asm', 'armips/asm', 'data/battle_scripts'):
        for dp, dn, fn in os.walk(R + d):
            if '/rh' in dp.replace('\\', '/'):
                continue
            for f in fn:
                if f.endswith(('.c', '.s', '.h')):
                    code += open(os.path.join(dp, f), encoding='utf-8', errors='replace').read()
    used = set(re.findall(r'\bABILITY_\w+', code))
    flags = open(R + 'data/AbilityFlags.c').read()
    fails_swap = set(re.findall(r'\[(ABILITY_\w+)\]\s*=\s*\{[^}]*failsSwap\s*=\s*TRUE', flags))
    impl = [0] * count
    swap = [0] * count
    for n, v in consts.items():
        if v == 0 or n in ('ABILITY_NONE',):
            continue
        if v <= VANILLA_LAST or n in used:
            impl[v] = 1
        if n in fails_swap:
            swap[v] = 1

    def bits(arr):
        words = [0] * ((count + 31) // 32)
        for i, b in enumerate(arr):
            if b:
                words[i // 32] |= 1 << (i % 32)
        return ', '.join(f'0x{w:08X}' for w in words)

    out = ['// AUTO-GENERATED by tools/rh/gen_rh_abilities.py - do not edit by hand.',
           f'#define RH_ABILITY_COUNT {count}',
           '// abilities that work in this engine (bit per ability id)',
           f'static const u32 sRhAbilityImplemented[] = {{ {bits(impl)} }};',
           '// form / signature abilities that are never randomized (failsSwap)',
           f'static const u32 sRhAbilityNoSwap[] = {{ {bits(swap)} }};']
    open(R + 'src/rh/rh_abilities.h', 'w', newline='\n').write('\n'.join(out) + '\n')
    names = {v: n for n, v in consts.items()}
    print('abilities', count, 'implemented', sum(impl), 'not implemented:',
          ' '.join(names[i][8:] for i in range(1, count) if not impl[i] and i in names))


if __name__ == '__main__':
    main()
