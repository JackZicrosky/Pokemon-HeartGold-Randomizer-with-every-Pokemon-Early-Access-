#!/usr/bin/env python3
"""Romhack: extracts the game's main font (a/0/1/6 member 0) for the randomizer options screen.

Writes src/rhmenu/rh_font.h: every character the menu uses, as 16x16 glyphs with 2 bits per pixel
(1 = text, 2 = shadow, 0/3 = nothing), plus its advance width. Characters the game font lacks
(▶ ‹ ›) are drawn here in the same style.

Usage (WSL, in source/, after a build extracted base/):  .venv/bin/python tools/rh/gen_rh_font.py
"""
import os
import struct

import ndspy.narc

R = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..')) + '/'

CHARS = [chr(c) for c in range(0x20, 0x7F)] + list('éÉ♂♀…‘’“”¥×←→↑↓★●■▲·~')
CUSTOM = {
    '▶': ['........', '.X......', '.XXX....', '.XXXXX..', '.XXXXXX.', '.XXXXX..', '.XXX....', '.X......'],
    '‹': ['........', '...X....', '..XX....', '.XXX....', '..XX....', '...X....', '........', '........'],
    '›': ['........', '.X......', '.XX.....', '.XXX....', '.XX.....', '.X......', '........', '........'],
}


def charmap():
    m = {}
    for line in open(R + 'charmap.txt', encoding='utf-8'):
        line = line.split('//')[0].rstrip('\n')
        if '=' not in line:
            continue
        k, v = line.split('=', 1)
        try:
            m.setdefault(v, int(k.strip(), 16))
        except ValueError:
            pass
    return m


def main():
    font = ndspy.narc.NARC(open(R + 'base/root/a/0/1/6', 'rb').read()).files[0]
    hs, wds, ng = struct.unpack_from('<III', font, 0)
    cm = charmap()
    missing = []
    glyphs = []   # (codepoint, 16 rows of u32: 2 bits per pixel, pixel 0 in the low bits, width)
    for ch in CHARS:
        code = cm[' '] if ch == ' ' else cm.get(ch)
        if code is None:
            missing.append(ch)       # not in the game font (", <, >, [, ^...): the menu never uses it
            continue
        gid = code - 1
        raw = font[hs + gid * 64: hs + gid * 64 + 64]
        rows = [0] * 16
        for t in range(4):
            tx, ty = (t % 2) * 8, (t // 2) * 8
            for r in range(8):
                b = raw[t * 16 + r * 2: t * 16 + r * 2 + 2]
                for c in range(8):
                    v = (b[1 - c // 4] >> (6 - 2 * (c % 4))) & 3
                    if v == 3:
                        v = 0
                    rows[ty + r] |= v << (2 * (tx + c))
        glyphs.append((ord(ch), rows, font[wds + gid]))
    # custom glyphs: text pixels with a shadow below-right, like the game font
    for ch, art in CUSTOM.items():
        rows = [0] * 16
        for y, line in enumerate(art):
            for x, p in enumerate(line):
                if p == 'X':
                    rows[y + 2] |= 1 << (2 * x)
        for y in range(15, 0, -1):
            for x in range(15, 0, -1):
                if (rows[y - 1] >> (2 * (x - 1))) & 3 == 1 and (rows[y] >> (2 * x)) & 3 == 0:
                    rows[y] |= 2 << (2 * x)
        glyphs.append((ord(ch), rows, 8))
    glyphs.sort()
    out = ['// AUTO-GENERATED by tools/rh/gen_rh_font.py from the game font - do not edit by hand.',
           '// 16x16 glyphs, 2 bits per pixel (1 text, 2 shadow), pixel x of row y = (rows[y] >> 2x) & 3.',
           f'#define RH_FONT_GLYPHS {len(glyphs)}',
           'struct RhGlyph { u16 codepoint; u8 width; u8 pad; u32 rows[16]; };',
           'static const struct RhGlyph sRhFont[RH_FONT_GLYPHS] = {']
    for cp, rows, w in glyphs:
        out.append(f'    {{ 0x{cp:04X}, {w}, 0, {{ ' + ', '.join(f'0x{r:08X}' for r in rows) + ' } },')
    out.append('};')
    os.makedirs(R + 'src/rhmenu', exist_ok=True)
    open(R + 'src/rhmenu/rh_font.h', 'w', newline='\n').write('\n'.join(out) + '\n')
    print('glyphs', len(glyphs), 'not in the font:', ''.join(missing))


if __name__ == '__main__':
    main()
