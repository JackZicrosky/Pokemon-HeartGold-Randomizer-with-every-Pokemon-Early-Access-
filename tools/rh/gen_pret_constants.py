#!/usr/bin/env python3
# Romhack: pret/pokeheartgold's constant headers (tools/rh/pret/constants) flattened into one header for map scripts
# imported from pret (tools/rh/import_pret_script.py). Every define is guarded, so hg-engine's own constants (included
# first) win where both define a name.
# Writes include/rh/pret_constants.h.
# Usage: python3 tools/rh/gen_pret_constants.py   (from the repository root)
import os
import re

SRC = 'tools/rh/pret/constants'


def main():
    out = ['// AUTO-GENERATED by tools/rh/gen_pret_constants.py from pret/pokeheartgold include/constants.',
           '#ifndef RH_PRET_CONSTANTS_H', '#define RH_PRET_CONSTANTS_H']
    seen = set()
    for f in sorted(os.listdir(SRC)):
        out.append('// %s' % f)
        for line in open(os.path.join(SRC, f), encoding='utf-8'):
            m = re.match(r'\s*#define\s+(\w+)(\([^)]*\))?\s*(.*?)\s*(//.*)?$', line.rstrip('\n'))
            if not m or m.group(1).endswith('_H') or line.rstrip().endswith('\\'):
                continue
            name = m.group(1)
            if name in seen:
                continue
            seen.add(name)
            out += ['#ifndef %s' % name, '#define %s%s %s' % (name, m.group(2) or '', m.group(3)), '#endif']
    out.append('#endif')
    open('include/rh/pret_constants.h', 'w', newline='\n').write('\n'.join(out) + '\n')
    print(len(seen), 'constants')


if __name__ == '__main__':
    main()
