#!/usr/bin/env python3
# Romhack: trainer tags for the Foe Pokemon randomizer (UPR FVX Gen4Constants.tagTrainersHGSS).
# Writes include/rh/rh_trainer_table.h: per trainer id its tier (boss / important / regular), FVX group
# (gyms, Elite Four, Champion, themed teams) and whether it is the rival; per group its official type.
# Usage: python3 tools/rh/gen_rh_trainers.py   (from the repository root)
import re

SRC = 'data/Trainers.c'
OUT = 'include/rh/rh_trainer_table.h'

TIER_BOSS, TIER_IMPORTANT, TIER_REGULAR = 0, 1, 2

# FVX groups: 1-16 = GYM1..GYM16, 17-20 = ELITE1..4, 21 = CHAMPION, 22.. = THEMED teams
GYMS = {
    1: [0x32, 0x1D], 2: [0x43, 0x44, 0x45, 0x0a], 3: [0x05, 0x46, 0x47, 0x16], 4: [0x1ed, 0x1ee, 0x59, 0x2e],
    5: [0x9c, 0x9d, 0x9f, 0xfb], 7: [0x1e0, 0x1e1, 0x1e2, 0x1e3, 0x1e4], 8: [0x6e, 0x6f, 0x70, 0x75, 0x77, 0x2DE],
    9: [0x134, 0x2ad], 10: [0x2a4, 0x2a5, 0x2a6, 0x129, 0x12a], 11: [0x18c, 0xe8, 0x151],
    12: [0x150, 0x146, 0x164, 0x15a], 13: [0x53, 0x54, 0xb7, 0x88], 14: [0x170, 0x171, 0xe6, 0x19f],
    15: [0x2b1, 0x2b2, 0x2b3, 0x2b4, 0x2b5, 0x2b6], 16: [0x2a9, 0x2aa, 0x2ab, 0x2ac],
}
LEADERS = {
    1: [0x14, 0x2c8], 2: [0x15, 0x2c9], 3: [0x1e, 0x2ca], 4: [0x1f, 0x2cb], 5: [0x22, 0x2ce], 6: [0x21, 0x2cd],
    7: [0x20, 0x2cc], 8: [0x23, 0x2cf], 9: [0xFD, 0x2d0], 10: [0xFE, 0x2d1], 11: [0xFF, 0x2d2], 12: [0x100, 0x2d3],
    13: [0x101, 0x2d4], 14: [0x102, 0x2d5], 15: [0x103, 0x2d6], 16: [0x105, 0x2d7],
}
ELITE = {17: [0xf5, 0x2be], 18: [0xf7, 0x2bf], 19: [0x1a2, 0x2c0], 20: [0xf6, 0x2c1]}   # Will, Koga, Bruno, Karen
CHAMPION = [0xf4, 0x2bd, 0x2DD]                                                         # Lance
UBER = [0x104]                                                                          # Red
OTHER_BOSS = [485]                                                                      # Archer ("LEADER")
KIMONO = [0xa0, 0xa1, 0xa2, 0xa3, 0xa4]                                                 # "STRONG"
THEMED = {22: ([0x1df, 0x1de], True), 23: ([0x1e8, 0x1e7], True), 24: ([0x1e6, 0x2c2], True),   # Ariana, Petrel, Proton
          25: ([0x2b, 0x33, 0x34, 0x35, 0x36, 0x37, 0x122], False)}                     # Sprout Tower
# Silver: every TRAINERCLASS_RIVAL battle, plus the first battle (Cherrygrove, class "Passerby" 0x1EF-0x1F1)
FIRST_RIVAL = [0x1EF, 0x1F0, 0x1F1]

# official type of each group (Johto then Kanto gyms, the Elite Four); Blue's gym and the Champion have none
GROUP_TYPE = {
    1: 'FLYING', 2: 'BUG', 3: 'NORMAL', 4: 'GHOST', 5: 'FIGHTING', 6: 'STEEL', 7: 'ICE', 8: 'DRAGON',
    9: 'ROCK', 10: 'WATER', 11: 'ELECTRIC', 12: 'GRASS', 13: 'POISON', 14: 'PSYCHIC', 15: 'FIRE',
    17: 'PSYCHIC', 18: 'POISON', 19: 'FIGHTING', 20: 'DARK',
}
NUM_GROUPS = 26


def main():
    src = open(SRC, encoding='utf-8').read()
    blocks = re.split(r'\n    \[(\d+)\] = \{', src)
    classes = {}
    for i in range(1, len(blocks), 2):
        classes[int(blocks[i])] = re.search(r'trainerClass = (\w+)', blocks[i + 1]).group(1)
    count = max(classes) + 1

    tier = [TIER_REGULAR] * count
    group = [0] * count
    rival = [0] * count
    for g, ids in GYMS.items():
        for t in ids:
            group[t] = g
    for g, ids in LEADERS.items():
        for t in ids:
            group[t], tier[t] = g, TIER_BOSS
    for g, ids in ELITE.items():
        for t in ids:
            group[t], tier[t] = g, TIER_BOSS
    for t in CHAMPION:
        group[t], tier[t] = 21, TIER_BOSS
    for t in UBER + OTHER_BOSS:
        tier[t] = TIER_BOSS
    for t in KIMONO:
        tier[t] = TIER_IMPORTANT
    for g, (ids, strong) in THEMED.items():
        for t in ids:
            group[t] = g
            if strong:
                tier[t] = TIER_IMPORTANT
    for t, c in classes.items():
        if c == 'TRAINERCLASS_RIVAL' or t in FIRST_RIVAL:
            rival[t] = 2 if t in FIRST_RIVAL else 1
            tier[t] = TIER_IMPORTANT

    out = ['// AUTO-GENERATED by tools/rh/gen_rh_trainers.py from data/Trainers.c and the UPR FVX HGSS trainer tags.',
           '// Bits 0-1 tier (0 boss, 1 important, 2 regular), bit 2 Silver, bit 3 his first battle; bits 8-15 group.',
           '#define RH_NUM_TRAINERS %d' % count,
           '#define RH_NUM_GROUPS %d' % NUM_GROUPS,
           '#define RH_GROUP_ELITE1 17',
           '#define RH_GROUP_CHAMPION 21',
           'static const u16 sRhTrainerTags[RH_NUM_TRAINERS] = {']
    line = '   '
    for t in range(count):
        v = tier[t] | (4 if rival[t] else 0) | (8 if rival[t] == 2 else 0) | (group[t] << 8)
        line += ' 0x%04X,' % v
        if len(line) > 110:
            out.append(line)
            line = '   '
    if line.strip():
        out.append(line)
    out.append('};')
    out.append('static const u8 sRhGroupType[RH_NUM_GROUPS] = {')
    out.append('    ' + ', '.join(('TYPE_' + GROUP_TYPE[g]) if g in GROUP_TYPE else 'RH_TYPE_NONE' for g in range(NUM_GROUPS)) + ',')
    out.append('};')
    # the Pokemon League (League Unique Pokemon): Will, Koga, Bruno, Karen, Lance
    out.append('static const u16 sRhLeagueMembers[5] = { 0xf5, 0xf7, 0x1a2, 0xf6, 0xf4 };')
    open(OUT, 'w', newline='\n').write('\n'.join(out) + '\n')
    print('wrote', OUT, count, 'trainers')


if __name__ == '__main__':
    main()
