#!/usr/bin/env python3
"""Romhack: species names for the options screen (custom starter fields), from data/Species.c.

Writes src/rhmenu/rh_names.h: one UTF-8 name per base species (1..SPECIES_MAX_MON_NUM), packed into
one string with offsets. Usage (WSL, in source/): python3 tools/rh/gen_rh_names.py
"""
import os
import re

R = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..')) + '/'


def main():
    src = open(R + 'data/Species.c', encoding='utf-8').read()
    names = {}
    for m in re.finditer(r'\[(SPECIES_\w+)\]\s*=\s*\{\s*\.textData\s*=\s*\{\s*\.name\s*=\s*"([^"]*)"', src):
        names[m.group(1)] = m.group(2)
    consts = {}
    for m in re.finditer(r'^#define\s+(SPECIES_\w+)\s+(\d+)\s*$', open(R + 'include/constants/species.h').read(), re.M):
        consts.setdefault(int(m.group(2)), m.group(1))
    last = max(i for i, n in consts.items() if n == 'SPECIES_PECHARUNT')
    blob, offs = b'', []
    for i in range(last + 1):
        n = names.get(consts.get(i, ''), '') if i else ''
        if n == '-----':
            n = ''
        offs.append(len(blob))
        blob += n.encode('utf-8') + b'\0'
    out = ['// AUTO-GENERATED by tools/rh/gen_rh_names.py from data/Species.c - do not edit by hand.',
           f'#define RH_NAME_COUNT {last + 1}',
           f'static const u16 sRhNameOffsets[RH_NAME_COUNT] = {{ {", ".join(map(str, offs))} }};',
           'static const char sRhNames[] =']
    line = ''
    for b in blob:
        line += f'\\{b:03o}' if b < 0x20 or b > 0x7e or chr(b) in '"\\' else chr(b)
        if len(line) > 100:
            out.append(f'    "{line}"')
            line = ''
    out.append(f'    "{line}";')
    open(R + 'src/rhmenu/rh_names.h', 'w', newline='\n').write('\n'.join(out) + '\n')
    print('names', last + 1, 'bytes', len(blob))


if __name__ == '__main__':
    main()
